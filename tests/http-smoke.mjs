import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';
const base=process.env.TEST_APP_URL??process.env.APP_URL;
assert.ok(base);
const client=createClient(process.env.NEXT_PUBLIC_MARKETPLACE_SUPABASE_URL,process.env.NEXT_PUBLIC_MARKETPLACE_SUPABASE_PUBLISHABLE_KEY,{auth:{persistSession:false}});
const listings=await client.from('listings').select('id,sold_at').limit(24);assert.ifError(listings.error);assert.ok(listings.data.length);
assert.ok((await client.from('orders').select()).error);assert.ok((await client.from('sellers').select()).error);
const item=listings.data.find(row=>!row.sold_at);assert.ok(item);
const availability=await fetch(base+'/api/checkout?listing_id='+item.id);assert.equal(availability.status,200);
const state=await availability.json();assert.equal(typeof state.ready,'boolean');
const post=(path,body,origin=base)=>fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json',Origin:origin},body:JSON.stringify(body)});
assert.equal((await post('/api/checkout',{listingId:item.id},'https://untrusted.example')).status,403);
assert.equal((await post('/api/checkout',{listingId:'bad',price:1})).status,400);
assert.equal((await post('/api/connect',{email:'bad'})).status,400);
if(!state.ready)assert.equal((await post('/api/checkout',{listingId:item.id,price:1})).status,409);
assert.equal((await fetch(base+'/api/orders/00000000-0000-4000-8000-000000000000')).status,404);
const unsigned=await fetch(base+'/api/stripe/webhook',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'});
assert.equal(unsigned.status,process.env.STRIPE_WEBHOOK_SECRET?400:503);
console.log('Passed: private tables, live availability, blocked cross-origin requests, invalid inputs, unready seller rejection, private order lookup, and unsigned webhook rejection. No records created.');
